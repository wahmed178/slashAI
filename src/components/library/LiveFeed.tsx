import { ExternalLink, Sparkles } from "lucide-react";

import dailyNewsRaw from "@/data/daily-news.json";
import dailyContentRaw from "@/data/daily-content.json";
import trendingPromptsRaw from "@/data/trending-prompts.json";

/* ═══════════════════════════════════════════════════════════════════
   LIVE FEED
   Renders the data that the scheduled GitHub Actions refresh:
     · daily-news.yml        → daily-news.json       (every day 07:00 UTC)
     · daily-content.yml     → daily-content.json    (every day 00:00 UTC)
     · weekly-trending-prompts.yml → trending-prompts.json (Wednesdays)
   Anything shown here is regenerated by a bot commit, so the page
   stays current without anyone editing code.
   ═══════════════════════════════════════════════════════════════════ */

type NewsItem = {
  title: string;
  url: string;
  source: string;
  score: number;
  publishedAt: string;
};

type PromptItem = {
  title: string;
  url: string;
  source: string;
  score: number;
  category: string;
  description: string;
};

type DailyContent = {
  updated: string;
  quote: { text: string; author: string };
  advice: string;
  artwork: { title: string; artist: string; imageId: string };
};

const dailyNews = dailyNewsRaw as unknown as { updated: string; articles: NewsItem[] };
const dailyContent = dailyContentRaw as unknown as DailyContent;
const trendingPrompts = trendingPromptsRaw as unknown as { updated: string; prompts: PromptItem[] };

/** "2026-09-18T10:45:42.161Z" or "2026-09-18" → "18 Sep 2026" */
function prettyDate(value: string): string {
  if (!value) return "";
  const d = new Date(value);
  if (Number.isNaN(d.getTime())) return value;
  return d.toLocaleDateString("en-GB", { day: "numeric", month: "short", year: "numeric" });
}

/** 170635 → "170.6k", 490 → "490" */
function compactScore(score: number): string {
  if (!score) return "";
  if (score >= 1000) return `${(score / 1000).toFixed(1).replace(/\.0$/, "")}k`;
  return String(score);
}

function SectionHeading({ title, note }: { title: string; note: string }) {
  return (
    <div className="flex flex-wrap items-baseline justify-between gap-2">
      <h2 className="text-sm font-semibold uppercase tracking-wide text-muted-foreground">{title}</h2>
      <span className="text-[11px] text-muted-foreground">{note}</span>
    </div>
  );
}

export function LiveFeed() {
  const articles = dailyNews.articles.slice(0, 6);
  const prompts = trendingPrompts.prompts.slice(0, 6);
  const quote = dailyContent.quote;
  const artwork = dailyContent.artwork;
  const hasSpark = Boolean(quote?.text || dailyContent.advice);

  return (
    <section className="mt-7">
      <SectionHeading
        title="Live"
        note={`Auto-updated ${prettyDate(dailyNews.updated || dailyContent.updated)}`}
      />

      <div className="mt-3 grid grid-cols-1 gap-2.5 lg:grid-cols-3">
        {/* ── Today in AI ─────────────────────────────────────────── */}
        <div className="rounded-[10px] border border-border bg-surface p-4 lg:col-span-2">
          <div className="flex items-center gap-2">
            <span className="inline-block size-2 rounded-full" style={{ background: "var(--primary)" }} />
            <h3 className="text-[13px] font-semibold text-foreground">Today in AI</h3>
          </div>

          {articles.length > 0 ? (
            <ul className="mt-3 flex flex-col divide-y divide-border">
              {articles.map((article) => (
                <li key={article.url} className="py-2.5 first:pt-0 last:pb-0">
                  <a
                    href={article.url}
                    target="_blank"
                    rel="noopener noreferrer"
                    className="group flex items-start justify-between gap-3"
                  >
                    <span className="min-w-0 flex-1 text-[13px] font-medium leading-snug text-foreground transition-colors group-hover:text-primary">
                      {article.title}
                    </span>
                    <ExternalLink className="mt-0.5 size-3 shrink-0 text-muted-foreground" />
                  </a>
                  <div className="mt-1 flex flex-wrap items-center gap-2 text-[11px] text-muted-foreground">
                    <span className="rounded border border-border bg-surface-elevated px-1.5 py-0.5">
                      {article.source}
                    </span>
                    {article.score > 0 && <span>▲ {compactScore(article.score)}</span>}
                    <span>{prettyDate(article.publishedAt)}</span>
                  </div>
                </li>
              ))}
            </ul>
          ) : (
            <p className="mt-3 text-[12px] text-muted-foreground">Fetching today's stories…</p>
          )}
        </div>

        {/* ── Today's spark ───────────────────────────────────────── */}
        <div className="rounded-[10px] border border-border bg-surface p-4">
          <div className="flex items-center gap-2">
            <Sparkles className="size-3.5" style={{ color: "var(--primary)" }} />
            <h3 className="text-[13px] font-semibold text-foreground">Today's spark</h3>
          </div>

          {hasSpark ? (
            <div className="mt-3 flex flex-col gap-3">
              {quote?.text && (
                <blockquote className="border-l-2 pl-3" style={{ borderColor: "var(--primary)" }}>
                  <p className="text-[13px] italic leading-relaxed text-foreground">{quote.text}</p>
                  {quote.author && (
                    <footer className="mt-1 text-[11px] text-muted-foreground">{quote.author}</footer>
                  )}
                </blockquote>
              )}

              {dailyContent.advice && (
                <div>
                  <p className="text-[11px] font-semibold uppercase tracking-wide text-muted-foreground">
                    Tip of the day
                  </p>
                  <p className="mt-1 text-[12px] leading-relaxed text-foreground">{dailyContent.advice}</p>
                </div>
              )}

              {artwork?.title && (
                <div>
                  <p className="text-[11px] font-semibold uppercase tracking-wide text-muted-foreground">
                    Art of the day
                  </p>
                  <p className="mt-1 text-[12px] leading-snug text-foreground">{artwork.title}</p>
                  <p className="text-[11px] text-muted-foreground">{artwork.artist}</p>
                </div>
              )}
            </div>
          ) : (
            <p className="mt-3 text-[12px] text-muted-foreground">Fetching today's pick…</p>
          )}
        </div>

        {/* ── Trending prompt repos ───────────────────────────────── */}
        {prompts.length > 0 && (
          <div className="rounded-[10px] border border-border bg-surface p-4 lg:col-span-3">
            <SectionHeading
              title="Trending prompt repos"
              note={`Refreshed ${prettyDate(trendingPrompts.updated)}`}
            />
            <div className="mt-3 grid grid-cols-1 gap-2.5 sm:grid-cols-2 lg:grid-cols-3">
              {prompts.map((prompt) => (
                <a
                  key={prompt.url}
                  href={prompt.url}
                  target="_blank"
                  rel="noopener noreferrer"
                  className="group flex flex-col rounded-[10px] border border-border bg-surface-elevated p-3 transition-all duration-150 hover:-translate-y-0.5 hover:border-primary/40"
                >
                  <div className="flex items-center justify-between gap-2">
                    <span className="truncate text-[13px] font-semibold text-foreground group-hover:text-primary">
                      {prompt.title}
                    </span>
                    <span className="shrink-0 text-[11px] text-muted-foreground">
                      ★ {compactScore(prompt.score)}
                    </span>
                  </div>
                  <p className="mt-1 line-clamp-2 text-[12px] leading-relaxed text-muted-foreground">
                    {prompt.description}
                  </p>
                  <span className="mt-2 self-start rounded border border-border px-1.5 py-0.5 text-[10px] text-muted-foreground">
                    {prompt.category}
                  </span>
                </a>
              ))}
            </div>
          </div>
        )}
      </div>
    </section>
  );
}

function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        {/* FOUC prevention: apply theme before any paint */}
        <script
          dangerouslySetInnerHTML={{
            __html: `try{var t=localStorage.getItem('slashai-theme');var p=window.matchMedia('(prefers-color-scheme:dark)').matches;if(t==='light'||(!t&&!p)){document.documentElement.classList.add('light')}}catch(e){}`,
          }}
        />
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();

  useEffect(() => {
    registerServiceWorker();
  }, []);

  // Scroll to top on every route change
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  const prevPathname = useRef(pathname);
  useEffect(() => {
    if (prevPathname.current !== pathname) {
      window.scrollTo(0, 0);
      prevPathname.current = pathname;
    }
  }, [pathname]);

  return (
    <QueryClientProvider client={queryClient}>
      <LibraryProvider>
        <KeyboardShortcutsProvider>
        {/* Splash removed — was causing infinite loading */}
        {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
        <Outlet />
        <WhatsNewDialog />
        <Toaster position="bottom-right" />
        </KeyboardShortcutsProvider>
      </LibraryProvider>
    </QueryClientProvider>
  );
}

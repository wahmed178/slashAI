/**
 * Writes src/lib/seo-counts.ts — the real catalogue totals, as plain numbers.
 *
 * Why a generated module: src/lib/seo.ts is imported by the root route, so it
 * must never pull a catalogue into the entry bundle (commands.json alone is
 * several MB). A file of literal numbers keeps titles and meta descriptions
 * honest without paying for the import — and because it is generated from the
 * catalogues, the numbers can never drift out of date again.
 *
 * Run: `bun run seo:counts` (also runs from `bun run seo:generate`).
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const j = async (p) => (await import(`../${p}`)).default;
const m = async (p) => await import(`../${p}`);

async function main() {
  const commandsSrc = await j("src/data/commands.json");
  const commands = Array.isArray(commandsSrc) ? commandsSrc : commandsSrc.commands ?? [];
  const categories = await j("src/data/categories.json");

  const subcategories = new Set();
  for (const c of commands) {
    if (c?.category && c?.subcategory) subcategories.add(`${c.category}|${c.subcategory}`);
  }

  // Use the app's own count constants so the meta text can never disagree
  // with the number the UI prints on the homepage and the hub pages.
  const { SLASH_TOOL_COUNT = 0 } = await m("src/lib/slashkits.ts");
  const { DECLARATIVE_TOOL_COUNT = 0 } = await m("src/lib/toolkit/catalog.ts");

  const { PLAY_GAME_COUNT = 0 } = await m("src/lib/slashplay.ts");
  const { COLLECTIONS = [] } = await m("src/lib/collections.ts");
  const { GLOSSARY_TOTAL = 0, GLOSSARY_CATEGORIES = [] } = await m("src/lib/glossary.ts");
  const { BUILD_IDEAS = [] } = await m("src/lib/build-ideas.ts");
  const { TOOLS: AI_TOOLS = [], TOOL_CATEGORIES = [] } = await m("src/lib/tools.ts");
  const { COURSES = [] } = await m("src/lib/courses.ts");
  const { ROADMAP_TOTAL = 0 } = await m("src/lib/roadmaps.ts");

  // Curated resources: the same five files the sitemap walks for /r/<id> pages.
  const resourceFiles = [
    "src/lib/resources.ts",
    "src/lib/resources-extra.ts",
    "src/lib/resources-catalog/apis.ts",
    "src/lib/resources-catalog/courses.ts",
    "src/lib/resources-catalog/youtube.ts",
  ].filter((f) => existsSync(f));
  const resourceIds = new Set();
  for (const file of resourceFiles) {
    for (const match of readFileSync(file, "utf8").matchAll(/^\s{4}id: "([a-z0-9-]+)",$/gm)) {
      resourceIds.add(match[1]);
    }
  }

  let lessons = 0;
  let testQuestions = 0;
  for (const course of COURSES) {
    for (const mod of course.modules ?? []) {
      lessons += (mod.lessons ?? []).length;
      testQuestions += (mod.test?.questions ?? mod.questions ?? []).length;
    }
  }

  // Note: deliberately no quiz-category count. /quiz loads its categories from
  // the Open Trivia DB at runtime, so any number baked here would be a guess.

  const counts = {
    commands: commands.length,
    categories: categories.length,
    subcategories: subcategories.size,
    tools: SLASH_TOOL_COUNT + DECLARATIVE_TOOL_COUNT,
    games: PLAY_GAME_COUNT,
    collections: COLLECTIONS.length,
    glossaryTerms: GLOSSARY_TOTAL,
    glossaryCategories: GLOSSARY_CATEGORIES.length,
    buildIdeas: BUILD_IDEAS.length,
    aiTools: AI_TOOLS.length,
    aiToolCategories: TOOL_CATEGORIES.length,
    courses: COURSES.length,
    lessons,
    testQuestions,
    roadmaps: ROADMAP_TOTAL,
    resources: resourceIds.size,
  };

  const body = Object.entries(counts)
    .map(([k, v]) => `  ${k}: ${v},`)
    .join("\n");

  writeFileSync(
    "src/lib/seo-counts.ts",
    `/**
 * AUTO-GENERATED by scripts/generate-seo-counts.mjs — do not edit by hand.
 * Real catalogue totals for the SEO layer. Regenerate with \`bun run seo:counts\`.
 */

export const SEO_COUNTS = {
${body}
} as const;
`,
  );

  /* ── the PWA manifest quotes the same totals, so keep it in step ── */
  const manifestPath = "public/manifest.webmanifest";
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  manifest.description = `Search and copy ${counts.commands.toLocaleString("en-US")} free AI slash commands, run ${counts.tools} browser tools, play ${counts.games} games and browse curated free resources - free forever, no account.`;
  writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

  console.log("seo-counts.ts + manifest.webmanifest written:", counts);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});

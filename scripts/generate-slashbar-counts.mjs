/**
 * Writes src/lib/slashbar-counts.ts — the real per-category row counts for the
 * SlashBar launcher, as plain literals.
 *
 * Why a generated module: the launcher used to call categorySummaries(), which
 * walks the whole 5.4 MB command catalogue plus the tools, games, guides and
 * resource tables to count the real rows behind every category. That put a
 * multi-megabyte chunk behind the overlay's lazy boundary, so tapping Slash in
 * the dock showed a "Loading SlashBar…" screen while the phone parsed it.
 * Literal counts let the launcher mount instantly, and because they are
 * generated from the same tables the UI reads, they can never drift from it.
 *
 * Run: `bun run slashbar:counts` (also runs from `bun run seo:generate`, and
 * therefore from every production build).
 */
import { writeFileSync } from "node:fs";

const m = async (p) => await import(`../${p}`);

async function main() {
  const { SLASH_CATEGORIES, categorySummaries } = await m("src/lib/slashbar-categories.ts");

  const rows = categorySummaries().map(({ def, counts }) => {
    // The one-line summary under each tile, built only from counts that are
    // non-zero so a tile never claims content its category does not hold.
    const summary = [
      counts.commands ? `${counts.commands.toLocaleString("en-US")} cmds` : null,
      counts.tools ? `${counts.tools} tools` : null,
      counts.games ? `${counts.games} games` : null,
      counts.articles ? `${counts.articles} guides` : null,
      counts.resources ? `${counts.resources} links` : null,
      counts.quotes ? `${counts.quotes} quotes` : null,
    ]
      .filter(Boolean)
      .join(" · ");

    return {
      slug: def.slug,
      name: def.name,
      emoji: def.emoji,
      summary,
      commands: counts.commands,
      tools: counts.tools,
      games: counts.games,
      articles: counts.articles,
      resources: counts.resources,
      quotes: counts.quotes,
      apps: counts.apps,
      total: counts.total,
    };
  });

  if (rows.length !== SLASH_CATEGORIES.length) {
    throw new Error(
      `categorySummaries() returned ${rows.length} rows for ${SLASH_CATEGORIES.length} categories`,
    );
  }
  for (const row of rows) {
    if (!(row.total > 0)) {
      throw new Error(`category "${row.slug}" has no rows — it would render as a dead page`);
    }
  }

  const body = rows
    .map((r) =>
      [
        "  {",
        `    slug: ${JSON.stringify(r.slug)},`,
        `    name: ${JSON.stringify(r.name)},`,
        `    emoji: ${JSON.stringify(r.emoji)},`,
        `    summary: ${JSON.stringify(r.summary)},`,
        `    commands: ${r.commands},`,
        `    tools: ${r.tools},`,
        `    games: ${r.games},`,
        `    articles: ${r.articles},`,
        `    resources: ${r.resources},`,
        `    quotes: ${r.quotes},`,
        `    apps: ${r.apps},`,
        `    total: ${r.total},`,
        "  },",
      ].join("\n"),
    )
    .join("\n");

  writeFileSync(
    "src/lib/slashbar-counts.ts",
    `/**
 * AUTO-GENERATED by scripts/generate-slashbar-counts.mjs — do not edit by hand.
 * Real row counts per SlashBar category, so the launcher can render its grid
 * without importing the command catalogue. Regenerate with \`bun run slashbar:counts\`.
 */

export interface SlashCategoryCount {
  slug: string;
  name: string;
  emoji: string;
  /** "2,340 cmds · 41 tools · 12 links" — only the buckets that are non-zero */
  summary: string;
  commands: number;
  tools: number;
  games: number;
  articles: number;
  resources: number;
  quotes: number;
  apps: number;
  total: number;
}

export const SLASHBAR_CATEGORY_COUNTS: SlashCategoryCount[] = [
${body}
];

export const SLASHBAR_CATEGORY_COUNT = SLASHBAR_CATEGORY_COUNTS.length;

/** Every indexed row across the categories — the number the launcher prints. */
export const SLASHBAR_INDEXED_ROWS = SLASHBAR_CATEGORY_COUNTS.reduce((n, c) => n + c.total, 0);
`,
  );

  console.log(
    `slashbar-counts.ts written: ${rows.length} categories, ${rows.reduce((n, r) => n + r.total, 0)} indexed rows`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
